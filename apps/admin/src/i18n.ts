const DICTS: Record<Locale, Record<string, string>> = { ru, en };

/** Перевод с fallback: locale → ru → opts.fallback → сам ключ. */
export function translate(locale: Locale, key: string, opts?: TOptions): string {
  let out: string = DICTS[locale][key] ?? ru[key] ?? opts?.fallback ?? key;
  const params = opts?.params;
  if (params !== undefined) {
    for (const [name, value] of Object.entries(params)) {
      out = out.split(`{${name}}`).join(String(value));
    }
  }
  return out;
}

export interface I18nApi {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, opts?: TOptions) => string;
}

export const I18nContext = createContext<I18nApi | null>(null);

/** Хук доступа к словарю: t("key", {params:{...}}). */
export function useT(): I18nApi {
  const ctx = useContext(I18nContext);
  if (ctx === null) throw new Error("I18nProvider отсутствует над деревом");
  return ctx;
}

/** Начальный язык: localStorage → ru (docs/30 §Ф5, default ru). */
export function initialLocale(): Locale {
  try {
    const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    if (stored === "en" || stored === "ru") return stored;
  } catch {
    // localStorage может быть недоступен (приватный режим) — молча берём ru
  }
  return "ru";
}

export function storeLocale(locale: Locale): void {
  try {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // см. initialLocale
  }
}
